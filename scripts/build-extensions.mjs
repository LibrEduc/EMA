/**
 * Compile extension pack authoring `.ts` → runtime ESM `.js`.
 *
 * Only files whose basename matches the loader contract are built:
 *   blocks.ts | generator.arduino.ts | generator.micropython.ts
 *
 * Usage: node scripts/build-extensions.mjs [packId…]
 *   (no args = all packs under extensions/)
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const RUNTIME_BASENAMES = new Set([
  "blocks.ts",
  "generator.arduino.ts",
  "generator.micropython.ts",
]);

const BANNER = `/**
 * @license
 * Copyright (C) 2023-2026 ASTUCE (Sébastien Canet microcompany)
 * SPDX-License-Identifier: GPL-3.0-or-later
 *
 * GENERATED by \`npm run build:extensions\` — do not edit by hand.
 * Source: sibling .ts (same basename).
 */
`;

function listPackDirs(requested) {
  const extRoot = path.join(PROJECT_ROOT, "extensions");
  const entries = fs.readdirSync(extRoot, { withFileTypes: true });
  const packs = entries
    .filter(
      (e) =>
        e.isDirectory() &&
        !e.name.startsWith("_") &&
        e.name !== "node_modules",
    )
    .map((e) => e.name);
  if (!requested.length) {
    return packs;
  }
  for (const id of requested) {
    if (!packs.includes(id)) {
      throw new Error(`Unknown extension pack: ${id}`);
    }
  }
  return requested;
}

function collectSources(packId) {
  const dir = path.join(PROJECT_ROOT, "extensions", packId);
  return fs
    .readdirSync(dir)
    .filter((name) => RUNTIME_BASENAMES.has(name))
    .map((name) => path.join(dir, name));
}

function transpileFile(tsPath) {
  const source = fs.readFileSync(tsPath, "utf8");
  const result = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2020,
      removeComments: false,
      esModuleInterop: true,
    },
    fileName: tsPath,
    reportDiagnostics: true,
  });
  if (result.diagnostics?.length) {
    const formatted = ts.formatDiagnosticsWithColorAndContext(
      result.diagnostics,
      {
        getCanonicalFileName: (f) => f,
        getCurrentDirectory: () => PROJECT_ROOT,
        getNewLine: () => "\n",
      },
    );
    throw new Error(`transpile failed for ${tsPath}:\n${formatted}`);
  }
  let js = result.outputText;
  js = js.replace(/^import\s+type\s+[^;]+;\s*\n/gm, "");
  js = js.replace(/^import\s+\{\s*\}\s+from\s+[^;]+;\s*\n/gm, "");
  const outPath = tsPath.replace(/\.ts$/, ".js");
  const body = js.replace(/^\/\*[\s\S]*?\*\/\s*/, "");
  fs.writeFileSync(outPath, `${BANNER}\n${body}`, "utf8");
  return outPath;
}

const requested = process.argv.slice(2);
const packs = listPackDirs(requested);
let count = 0;
for (const packId of packs) {
  const sources = collectSources(packId);
  if (!sources.length) {
    console.log(`[build:extensions] ${packId}: no runtime .ts sources`);
    continue;
  }
  for (const src of sources) {
    const out = transpileFile(src);
    console.log(
      `[build:extensions] ${path.relative(PROJECT_ROOT, src)} → ${path.basename(out)}`,
    );
    count++;
  }
}
console.log(`[build:extensions] done (${count} file(s))`);
