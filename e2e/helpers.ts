/** Types into a field the way a student does: click it, replace the text, press Enter. */
export async function editField(
  page: Page,
  blockId: string,
  field: string,
  text: string,
): Promise<void> {
  const editor = page.locator(".blocklyHtmlInput");
  // A click that lands while the block is still re-laying out opens nothing: click again.
  await expect(async () => {
    await clickField(page, blockId, field);
    await expect(editor).toBeFocused({ timeout: 1_500 });
  }).toPass();
  await page.keyboard.press("Control+a");
  await page.keyboard.type(text);
  await page.keyboard.press("Enter");
  await expect(editor).toBeHidden();
}

