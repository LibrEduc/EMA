/** Real mouse drag of one block from the flyout onto the target. Returns the new block id. */
export async function dragFromFlyout(
  page: Page,
  wanted: FlyoutBlock,
  target: DropTarget,
): Promise<string> {
  await openCategory(page, wanted.category);
  const grab = await scrollFlyoutTo(page, wanted);
  const before = await blockIds(page);

  await page.mouse.move(grab.point.x, grab.point.y);
  await page.mouse.down();
  await page.mouse.move(grab.point.x + 12, grab.point.y + 12, { steps: 3 });

  // Starting the drag closes the flyout and moves the layout: aim only once it has settled.
  let lastAim = "";
  let aim: Point = { x: 0, y: 0 };
  await expect
    .poll(async () => {
      aim = await dropPoint(page, wanted, target);
      const settled = JSON.stringify(aim) === lastAim;
      lastAim = JSON.stringify(aim);
      return settled;
    })
    .toBe(true);

  const end = { x: aim.x + grab.offset.x, y: aim.y + grab.offset.y };
  if (!("x" in target)) {
    // Come in from the right on the target row: no other connection is crossed on the way.
    await page.mouse.move(780, end.y, { steps: 8 });
  }
  await page.mouse.move(end.x, end.y, { steps: 20 });
  await page.mouse.up();

  await expect.poll(async () => (await newBlockIds(page, before)).length).toBe(1);
  return (await newBlockIds(page, before))[0];
}

async function openCategory(page: Page, label: string): Promise<void> {
  const flyoutVisible = () =>
    page.evaluate(() => (window.__blockly.getMainWorkspace() as WorkspaceSvg).getFlyout()!.isVisible());
  // The row is covered by its own container, hence the forced click.
  const clickRow = () =>
    page.locator(".blocklyToolboxCategory", { hasText: label }).first().click({ force: true });
  // The click scrolls the flyout to the category. It closes the flyout when the category
  // is already selected, and is lost while the flyout is still closing: click until it shows.
  await clickRow();
  await expect(async () => {
    if (!(await flyoutVisible())) await clickRow();
    expect(await flyoutVisible()).toBe(true);
  }).toPass({ timeout: 5_000 });
}

async function clickField(page: Page, blockId: string, field: string): Promise<void> {
  const centre = await settledPoint(page, () =>
    page.evaluate(
      ({ id, name }) => {
        const box = window.__blockly
          .getMainWorkspace()
          .getBlockById(id)!
          .getField(name)!
          .getSvgRoot()!
          .getBoundingClientRect();
        return { x: box.left + box.width / 2, y: box.top + box.height / 2 };
      },
      { id: blockId, name: field },
    ),
  );
  await page.mouse.click(centre.x, centre.y);
}

/** A freshly dropped block slides into place: wait until two reads of its position agree. */
async function settledPoint(page: Page, read: () => Promise<Point>): Promise<Point> {
  let previous = "";
  let point: Point = { x: 0, y: 0 };
  await expect
    .poll(async () => {
      point = await read();
      const unchanged = JSON.stringify(point) === previous;
      previous = JSON.stringify(point);
      return unchanged;
    })
    .toBe(true);
  return point;
}

async function blockIds(page: Page): Promise<string[]> {
  return page.evaluate(() =>
    window.__blockly
      .getMainWorkspace()
      .getAllBlocks(false)
      .filter((block) => !block.isShadow())
      .map((block) => block.id),
  );
}

async function newBlockIds(page: Page, before: string[]): Promise<string[]> {
  return (await blockIds(page)).filter((id) => !before.includes(id));
}

/** Wheel-scrolls the flyout until the block shows, and waits for its animation to stop. */
async function scrollFlyoutTo(page: Page, wanted: FlyoutBlock): Promise<GrabPoint> {
  let previous = "";
  let stable: GrabPoint | null = null;
  await expect
    .poll(
      async () => {
        const seen = await flyoutGrabPoint(page, wanted);
        if (seen === null || "scroll" in seen) {
          previous = "";
          if (seen) {
            await page.mouse.move(700, 300);
            await page.mouse.wheel(0, seen.scroll);
          }
          return false;
        }
        const unchanged = JSON.stringify(seen) === previous;
        previous = JSON.stringify(seen);
        stable = unchanged ? seen : null;
        return unchanged;
      },
      { message: `flyout block ${wanted.type} stays in view` },
    )
    .toBe(true);
  return stable as unknown as GrabPoint;
}

async function flyoutGrabPoint(
  page: Page,
  wanted: FlyoutBlock,
): Promise<GrabPoint | { scroll: number } | null> {
  return page.evaluate((spec) => {
    const workspace = window.__blockly.getMainWorkspace() as WorkspaceSvg;
    const flyout = workspace.getFlyout()!;
    const flyoutWorkspace = flyout.getWorkspace() as WorkspaceSvg;
    const candidate = flyoutWorkspace
      .getTopBlocks(true)
      .find(
        (block) =>
          block.type === spec.type &&
          Object.entries(spec.fields ?? {}).every(
            ([name, value]) =>
              block.getFieldValue(name) === value ||
              block.getField(name)?.getText() === value,
          ),
      );
    if (!candidate) {
      return null;
    }
    const box = candidate.getSvgRoot().getBoundingClientRect();
    const view = flyoutWorkspace.getParentSvg().getBoundingClientRect();
    // The search bar shifts the flyout down: its bottom can lie below the visible workspace.
    const visibleBottom = Math.min(
      view.bottom,
      workspace.getInjectionDiv().getBoundingClientRect().bottom,
    );
    if (box.top < view.top + 4 || box.bottom > visibleBottom - 4) {
      return { scroll: box.top - view.top - view.height / 2 };
    }
    const offset = { x: 12, y: Math.min(14, box.height / 2) };
    return { point: { x: box.left + offset.x, y: box.top + offset.y }, offset };
  }, wanted);
}

/** Screen position where the dragged block's top-left corner must be for its plug to meet the target. */
async function dropPoint(
  page: Page,
  wanted: FlyoutBlock,
  target: DropTarget,
): Promise<Point> {
  if ("x" in target) {
    return target;
  }
  return page.evaluate(
    ({ spec, where }) => {
      const workspace = window.__blockly.getMainWorkspace() as WorkspaceSvg;
      const parent = workspace.getBlockById(where.blockId)!;
      const socket =
        "next" in where
          ? parent.nextConnection!
          : parent.getInput(where.input)!.connection!;
      const flyoutBlock = workspace
        .getFlyout()!
        .getWorkspace()
        .getTopBlocks(true)
        .find(
          (block) =>
            block.type === spec.type &&
            Object.entries(spec.fields ?? {}).every(
              ([name, value]) =>
                block.getFieldValue(name) === value ||
                block.getField(name)?.getText() === value,
            ),
        )!;
      const plug = flyoutBlock.outputConnection ?? flyoutBlock.previousConnection!;
      const origin = flyoutBlock.getRelativeToSurfaceXY();
      const toScreen = workspace.getCanvas().getScreenCTM()!;
      return {
        x: toScreen.a * (socket.x - (plug.x - origin.x)) + toScreen.e,
        y: toScreen.d * (socket.y - (plug.y - origin.y)) + toScreen.f,
      };
    },
    { spec: wanted, where: target },
  );
}

/** Drags a placed block onto the trash can, once the block has stopped moving. */
export async function dragToTrash(page: Page, blockId: string): Promise<void> {
  const grab = await settledPoint(page, () =>
    page.evaluate((id) => {
      const block = window.__blockly
        .getMainWorkspace()
        .getBlockById(id) as import("blockly").BlockSvg;
      const box = block.getSvgRoot().getBoundingClientRect();
      return { x: box.left + 10, y: box.top + 10 };
    }, blockId),
  );
  const trash = (await page.locator(".blocklyTrash").boundingBox())!;
  await page.mouse.move(grab.x, grab.y);
  await page.mouse.down();
  await page.mouse.move(trash.x + trash.width / 2, trash.y + trash.height / 2, { steps: 15 });
  await page.mouse.up();
}
