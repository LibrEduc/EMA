import { expect, test as base, type Page } from "@playwright/test";

export type CodeTarget = "arduino" | "micropython";

/** A block of the flyout, found by type and, when needed, by a field value or label. */
export interface FlyoutBlock {
  category: string;
  type: string;
  fields?: Record<string, string>;
}

/** Where a dragged block lands: a free screen point, or a connection of a block already placed. */
export type DropTarget =
  | { x: number; y: number }
  | { blockId: string; input: string }
  | { blockId: string; next: true };

interface Point {
  x: number;
  y: number;
}

interface GrabPoint {
  point: Point;
  offset: Point;
}

type WorkspaceSvg = import("blockly").WorkspaceSvg;

declare global {
  interface Window {
    __blockly: typeof import("blockly");
  }
}

export interface App {
  page: Page;
  /** Console errors, console warnings and uncaught page errors since the page opened. */
  problems: string[];
}

export const test = base.extend<{ app: App }>({
  app: async ({ page }, use) => {
    const problems: string[] = [];
    page.on("console", (message) => {
      if (message.type() === "error" || message.type() === "warning") {
        problems.push(`${message.type()}: ${message.text()}`);
      }
    });
    page.on("pageerror", (error) => problems.push(`pageerror: ${error.message}`));
    // No network, as in competitions (#22): the font CDNs get an empty stylesheet, not an error.
    await page.route(/fonts\.googleapis\.com|fonts\.gstatic\.com|cdn\.jsdelivr\.net/, (route) =>
      route.fulfill({ status: 200, contentType: "text/css", body: "" }),
    );

    await page.goto("/");
    await page.locator(".blocklySvg").first().waitFor();
    // Dev server only: the pre-bundled module is the very same Blockly instance the app uses.
    await page.evaluate(async () => {
      const url = performance
        .getEntriesByType("resource")
        .map((entry) => entry.name)
        .find((name) => /\.vite\/deps\/blockly\.js/.test(name));
      if (!url) throw new Error("Blockly was not loaded from .vite/deps: is this the Vite dev server?");
      window.__blockly = await import(/* @vite-ignore */ url);
    });
    await expect(page.locator("#ema-code")).not.toBeEmpty();
    await use({ page, problems });
  },
});

export { expect };

export async function openSettings(page: Page): Promise<void> {
  const settings = page.locator("details.ema-settings");
  if (!(await settings.evaluate((el: HTMLDetailsElement) => el.open))) {
    await settings.locator("summary").click();
  }
}

export async function closeSettings(page: Page): Promise<void> {
  const settings = page.locator("details.ema-settings");
  if (await settings.evaluate((el: HTMLDetailsElement) => el.open)) {
    await settings.locator("summary").click();
  }
}

export async function showCode(page: Page, target: CodeTarget): Promise<void> {
  const drawer = page.locator(".ema-code-drawer");
  if (!(await drawer.evaluate((el: HTMLDetailsElement) => el.open))) {
    await drawer.locator("summary").click();
  }
  await openSettings(page);
  await page.locator(`label:has(input[value="${target}"])`).click();
  await expect(page.locator(`input[value="${target}"]`)).toBeChecked();
  await closeSettings(page);
}

/** Generated code without its two-line header, which carries a timestamp. */
export async function readCode(page: Page): Promise<string> {
  const text = (await page.locator("#ema-code").textContent()) ?? "";
  return text.replace(/^(?:(?:#|\/\/) (?:Generated by|\d{4}-).*\n)+/, "").trim();
}

/** Waits for the debounced code panel to show exactly `expected` in the given target. */
export async function expectCode(
  page: Page,
  target: CodeTarget,
  expected: string,
): Promise<void> {
  await showCode(page, target);
  await expect.poll(async () => journeyPart(target, await readCode(page))).toBe(expected.trim());
}

// The MicroPython header (imports, variables, functions) is pinned by the unit tests;
// journeys compare from the setup on, so a new header line does not break them all.
function journeyPart(target: CodeTarget, code: string): string {
  const setup = code.indexOf("# --- setup ---");
  return target === "micropython" && setup >= 0 ? code.slice(setup) : code;
}

