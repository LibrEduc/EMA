import { afterEach, describe, expect, it, vi } from "vitest";
import type { GenerationResult, UnsupportedBlock } from "./codegen";
import { getShellCopy, type UiLanguage } from "./i18n";
import {
  HUB_SLOT_MAX,
  HUB_SLOT_MIN,
  downloadHubProgram,
  formatHubFilename,
  formatHubIssueMessage,
  getHubExportIssue,
  isValidHubSlot,
  normalizeHubSlot,
} from "./hub_export";

describe("hub_export (#21 / #12)", () => {
  afterEach(() => {
    vi.unstubAllGlobals();
    vi.restoreAllMocks();
  });

  it("exposes slots 0 to 19", () => {
    expect(HUB_SLOT_MIN).toBe(0);
    expect(HUB_SLOT_MAX).toBe(19);
  });

  it("validates integer slots in [0, 19]", () => {
    expect(isValidHubSlot(0)).toBe(true);
    expect(isValidHubSlot(7)).toBe(true);
    expect(isValidHubSlot(19)).toBe(true);
    expect(isValidHubSlot(-1)).toBe(false);
    expect(isValidHubSlot(20)).toBe(false);
    expect(isValidHubSlot(1.5)).toBe(false);
    expect(isValidHubSlot(Number.NaN)).toBe(false);
  });

  it("normalizes and clamps slot inputs", () => {
    expect(normalizeHubSlot(0)).toBe(0);
    expect(normalizeHubSlot(12)).toBe(12);
    expect(normalizeHubSlot("12")).toBe(12);
    expect(normalizeHubSlot(-5)).toBe(0);
    expect(normalizeHubSlot(42)).toBe(19);
    expect(normalizeHubSlot(null)).toBe(0);
    expect(normalizeHubSlot(undefined)).toBe(0);
    expect(normalizeHubSlot("abc")).toBe(0);
  });

  it("formats Hub filenames as prog_N.py", () => {
    expect(formatHubFilename(0)).toBe("prog_0.py");
    expect(formatHubFilename(3)).toBe("prog_3.py");
    expect(formatHubFilename(19)).toBe("prog_19.py");
    expect(formatHubFilename(99)).toBe("prog_19.py");
  });

  it("downloads prog_N.py via a Blob object URL and revokes it", () => {
    const click = vi.fn();
    const remove = vi.fn();
    const link = {
      href: "",
      download: "",
      style: { display: "" },
      click,
      remove,
    };
    const append = vi.fn();

    vi.stubGlobal("document", {
      createElement: vi.fn((tag: string) => {
        expect(tag).toBe("a");
        return link;
      }),
      body: { appendChild: append },
    });

    const createObjectURL = vi.fn((_blob: Blob) => "blob:ema-test");
    const revokeObjectURL = vi.fn((_url: string) => undefined);
    vi.stubGlobal("URL", { createObjectURL, revokeObjectURL });

    const filename = downloadHubProgram("print('MAE')\n", 3);

    expect(filename).toBe("prog_3.py");
    expect(createObjectURL).toHaveBeenCalledTimes(1);
    const blobArg = createObjectURL.mock.calls[0]?.[0];
    expect(blobArg).toBeInstanceOf(Blob);
    expect(blobArg.type).toContain("python");
    expect(link.download).toBe("prog_3.py");
    expect(link.href).toBe("blob:ema-test");
    expect(append).toHaveBeenCalledWith(link);
    expect(click).toHaveBeenCalledTimes(1);
    expect(remove).toHaveBeenCalledTimes(1);
    expect(revokeObjectURL).toHaveBeenCalledWith("blob:ema-test");
  });
});

const IDLE_PROGRAM = [
  "# Generated by EMA (MicroPython)",
  "# 2026-11-24T00:00:00.000Z",
  "",
  "# --- setup ---",
  "",
  "# --- loop ---",
  "while True:",
  "  pass",
  "",
].join("\n");

const REAL_PROGRAM = [
  "# Generated by EMA (MicroPython)",
  "# 2026-11-24T00:00:00.000Z",
  "",
  "import time",
  "",
  "# --- loop ---",
  "while True:",
  "  time.sleep(1)",
  "",
].join("\n");

const generated = (code: string): GenerationResult => ({ ok: true, code });
const failed = (
  unsupportedBlocks: ReadonlyArray<UnsupportedBlock>,
): GenerationResult => ({ ok: false, error: new Error("x"), unsupportedBlocks });

describe("getHubExportIssue (revue PR #32)", () => {
  it("refuses a failed generation", () => {
    expect(getHubExportIssue(failed([]))).toBe("generationError");
  });

  it("refuses an empty or blank program", () => {
    expect(getHubExportIssue(generated(""))).toBe("emptyProgram");
    expect(getHubExportIssue(generated("  \n\t\n"))).toBe("emptyProgram");
  });

  it("refuses the idle loop generated for an empty setup/loop block", () => {
    expect(getHubExportIssue(generated(IDLE_PROGRAM))).toBe("emptyProgram");
  });

  it("refuses a program that only holds comments", () => {
    expect(getHubExportIssue(generated("# un commentaire\n"))).toBe(
      "emptyProgram",
    );
  });

  it("refuses a program that only holds imports", () => {
    expect(getHubExportIssue(generated("import time\n"))).toBe("emptyProgram");
    expect(
      getHubExportIssue(generated("from machine import Pin\n\nimport time\n")),
    ).toBe("emptyProgram");
  });

  it("accepts a program with at least one real statement", () => {
    expect(getHubExportIssue(generated(REAL_PROGRAM))).toBeNull();
  });
});

describe("formatHubIssueMessage", () => {
  const copy = {
    hubErrorBlocks: "Blocs non pris en charge : {blocks}.",
    hubErrorGeneric: "La génération a échoué.",
    hubErrorEmpty: "Le programme est vide.",
    hubFreeBlock: "Bloc libre ({role})",
    hubFreeRoles: {
      value: "valeur",
      instruction: "instruction",
      start: "début de pile",
      end: "fin de pile",
      loop: "boucle",
      innerLoop: "boucle au milieu",
    },
  };

  it("names a Libre block by its role when it holds no text", () => {
    const result = failed([{ id: "1", type: "libre_start", label: "" }]);

    expect(formatHubIssueMessage(copy, "generationError", result)).toBe(
      "Blocs non pris en charge : « Bloc libre (début de pile) ».",
    );
  });

  it("gives every Libre block type a readable role name", () => {
    const types = [
      "libre_in",
      "libre_out",
      "libre_in_out",
      "libre_start",
      "libre_end",
      "libre_loop",
      "libre_loop_with_return",
      "libre_loop_inside",
      "libre_loop_inside_in",
      "libre_loop_inside_in_mutator",
      "libre_loop_do_inside",
      "libre_loop_do_inside_in",
    ];
    for (const type of types) {
      const message = formatHubIssueMessage(
        copy,
        "generationError",
        failed([{ id: "1", type, label: "" }]),
      );
      expect(message, type).toContain("Bloc libre (");
      expect(message, type).not.toContain(type);
    }
  });

  it("prefers the text typed in the block over its role", () => {
    const result = failed([{ id: "1", type: "libre_start", label: "mon code" }]);

    expect(formatHubIssueMessage(copy, "generationError", result)).toBe(
      "Blocs non pris en charge : « mon code ».",
    );
  });

  it("shows text typed by a student literally, even with replace patterns", () => {
    const typed = "$& $' $` $1 $$ <b>x</b>";
    const result = failed([{ id: "1", type: "libre_start", label: typed }]);

    expect(formatHubIssueMessage(copy, "generationError", result)).toBe(
      `Blocs non pris en charge : « ${typed} ».`,
    );
  });

  it("falls back to the block type when it has neither text nor role", () => {
    const result = failed([{ id: "1", type: "autre_bloc", label: "" }]);

    expect(formatHubIssueMessage(copy, "generationError", result)).toBe(
      "Blocs non pris en charge : « autre_bloc ».",
    );
  });

  it("names the unsupported block", () => {
    const result = failed([{ id: "1", type: "t", label: "allumer LED" }]);

    expect(formatHubIssueMessage(copy, "generationError", result)).toBe(
      "Blocs non pris en charge : « allumer LED ».",
    );
  });

  it("names three blocks at most and counts the others", () => {
    const result = failed(
      ["a", "b", "c", "d", "e"].map((label) => ({ id: label, type: "t", label })),
    );

    expect(formatHubIssueMessage(copy, "generationError", result)).toBe(
      "Blocs non pris en charge : « a », « b », « c » (+2).",
    );
  });

  it("falls back to a generic message when no block is identified", () => {
    expect(formatHubIssueMessage(copy, "generationError", failed([]))).toBe(
      "La génération a échoué.",
    );
  });

  it("explains an empty program", () => {
    expect(
      formatHubIssueMessage(copy, "emptyProgram", generated(IDLE_PROGRAM)),
    ).toBe("Le programme est vide.");
  });
});

describe("Hub messages in every interface language", () => {
  const languages: UiLanguage[] = ["fr", "en", "es", "ar"];

  it("defines a distinct name for each Libre block role", () => {
    for (const language of languages) {
      const copy = getShellCopy(language);
      const roles = Object.values(copy.hubFreeRoles);

      expect(copy.hubFreeBlock, language).toContain("{role}");
      expect(roles, language).toHaveLength(6);
      expect(new Set(roles).size, language).toBe(6);
      expect(
        roles.every((role) => role.trim() !== ""),
        language,
      ).toBe(true);
    }
  });

  it("keeps the {blocks} placeholder in the unsupported-blocks message", () => {
    for (const language of languages) {
      expect(getShellCopy(language).hubErrorBlocks, language).toContain(
        "{blocks}",
      );
    }
  });
});
