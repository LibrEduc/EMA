/**
 * Générateur MicroPython côté coquille EMA.
 * Le noyau µcBlockly ne fournit que Arduino C++ ; MicroPython est fourni par l’hôte.
 */

import type { Block } from "blockly/core";
import type { Workspace } from "blockly";
import { Order, PythonGenerator, pythonGenerator } from "blockly/python";

type StatementFn = (block: Block, generator: MicroPythonGenerator) => string;
type ValueFn = (
  block: Block,
  generator: MicroPythonGenerator,
) => [string, number];

export class MicroPythonGenerator extends PythonGenerator {
  setups_: Record<string, string> = {};
  loops_: Record<string, string> = {};
  imports_ = new Set<string>();

  constructor() {
    super("MicroPython");
    // Réutilise les générateurs standard Blockly Python (logique, math, texte…).
    Object.assign(this.forBlock, pythonGenerator.forBlock);
    registerBoardGenerators(this);
  }

  addSetup(key: string, code: string): void {
    this.setups_[key] = code;
  }

  addLoop(key: string, code: string): void {
    this.loops_[key] = code;
  }

  addImport(line: string): void {
    this.imports_.add(line);
  }

  override init(workspace: Workspace): void {
    this.setups_ = {};
    this.loops_ = {};
    this.imports_ = new Set();
    super.init(workspace);
  }

  override finish(code: string): string {
    const hasSetupTag = Object.keys(this.setups_).length > 0;
    const hasLoopTag = Object.keys(this.loops_).length > 0;
    const setupBody = Object.values(this.setups_)
      .map((s) => s.trimEnd())
      .filter(Boolean)
      .join("\n");
    const loopFromTags = Object.values(this.loops_)
      .map((s) => s.trimEnd())
      .filter(Boolean)
      .join("\n");
    const loose = code.trim();
    const loopBody = [loopFromTags, loose].filter(Boolean).join("\n");
    const emitLoop = hasLoopTag || Boolean(loose);

    super.finish(code);

    if (!hasSetupTag && !emitLoop && this.imports_.size === 0) {
      return "";
    }

    const lines: string[] = [
      "# Generated by EMA (MicroPython)",
      `# ${new Date().toISOString()}`,
      "",
    ];

    const imports = [...this.imports_].sort();
    if (imports.length > 0) {
      lines.push(...imports, "");
    }

    if (hasSetupTag) {
      lines.push("# --- setup ---");
      if (setupBody) {
        lines.push(setupBody);
      }
      lines.push("");
    }

    if (emitLoop) {
      lines.push("# --- loop ---", "while True:");
      if (loopBody) {
        for (const raw of loopBody.split("\n")) {
          lines.push(raw.trim().length === 0 ? "" : `  ${raw}`);
        }
      } else {
        lines.push("  pass");
      }
      lines.push("");
    }

    return lines.join("\n");
  }
}

export const micropythonGenerator = new MicroPythonGenerator();

function register(
  gen: MicroPythonGenerator,
  type: string,
  fn: StatementFn | ValueFn,
): void {
  gen.forBlock[type] = fn as (typeof gen.forBlock)[string];
}

function pinExpr(block: Block, gen: MicroPythonGenerator, name = "PIN"): string {
  const field = block.getFieldValue(name);
  if (field !== null && field !== undefined && field !== "") {
    return String(field);
  }
  return gen.valueToCode(block, name, Order.ATOMIC) || "0";
}

// statementToCode indents its body, but setup runs at module level and
// finish() indents the loop itself.
function unindentedStatements(
  block: Block,
  inputName: string,
  gen: MicroPythonGenerator,
): string {
  const leadingIndent = new RegExp(`^${gen.INDENT}`, "gm");
  return gen.statementToCode(block, inputName).replace(leadingIndent, "");
}

function registerBoardGenerators(gen: MicroPythonGenerator): void {
  register(gen, "board_base_setup", (block, g) => {
    g.addSetup("base_setup", unindentedStatements(block, "SETUP", g));
    return "";
  });

  register(gen, "board_base_loop", (block, g) => {
    g.addLoop("base_loop", unindentedStatements(block, "LOOP", g));
    return "";
  });

  register(gen, "board_base_setup_loop", (block, g) => {
    g.addSetup("base_setup", unindentedStatements(block, "SETUP", g));
    g.addLoop("base_loop", unindentedStatements(block, "LOOP", g));
    return "";
  });

  register(gen, "board_base_time_delay", (block, g) => {
    g.addImport("import time");
    const ms = g.valueToCode(block, "DELAY_TIME", Order.ATOMIC) || "1000";
    return `time.sleep_ms(int(${ms}))\n`;
  });

  register(gen, "board_base_time_delay_sec", (block, g) => {
    g.addImport("import time");
    const sec = g.valueToCode(block, "DELAY_TIME", Order.ATOMIC) || "1";
    return `time.sleep(float(${sec}))\n`;
  });

  register(gen, "board_base_time_millis", () => {
    gen.addImport("import time");
    return ["time.ticks_ms()", Order.FUNCTION_CALL];
  });

  register(gen, "board_base_inout_highlow", (block) => {
    const v = block.getFieldValue("BOOL") === "HIGH" ? "1" : "0";
    return [v, Order.ATOMIC];
  });

  register(gen, "board_base_inout_buildin_led", (block, g) => {
    g.addImport("from machine import Pin");
    const stat = block.getFieldValue("STAT") === "HIGH" ? "1" : "0";
    g.addSetup(
      "setup_led",
      "led = Pin('LED', Pin.OUT) if hasattr(Pin.board, 'LED') else Pin(25, Pin.OUT)",
    );
    return `led.value(${stat})\n`;
  });

  register(gen, "board_base_inout_digital_write", (block, g) => {
    g.addImport("from machine import Pin");
    const pin = pinExpr(block, g);
    const stat = block.getFieldValue("STAT") === "HIGH" ? "1" : "0";
    g.addSetup(`setup_out_${pin}`, `pin_${pin} = Pin(${pin}, Pin.OUT)`);
    return `pin_${pin}.value(${stat})\n`;
  });

  register(gen, "board_base_inout_digital_read", (block, g) => {
    g.addImport("from machine import Pin");
    const pin = pinExpr(block, g);
    g.addSetup(`setup_in_${pin}`, `pin_${pin} = Pin(${pin}, Pin.IN)`);
    return [`pin_${pin}.value()`, Order.FUNCTION_CALL];
  });

  register(gen, "board_base_inout_digital_read_pin", (block, g) => {
    g.addImport("from machine import Pin");
    const pin = g.valueToCode(block, "PIN", Order.ATOMIC) || "0";
    g.addSetup(`setup_in_dyn_${block.id}`, `pin_dyn = Pin(${pin}, Pin.IN)`);
    return ["pin_dyn.value()", Order.FUNCTION_CALL];
  });

  register(gen, "board_base_inout_analog_write", (block, g) => {
    g.addImport("from machine import Pin, PWM");
    const pin = pinExpr(block, g);
    const val = g.valueToCode(block, "NUM", Order.ATOMIC) || "0";
    g.addSetup(`setup_pwm_${pin}`, `pwm_${pin} = PWM(Pin(${pin}))`);
    return `pwm_${pin}.duty_u16(int((${val}) * 257))\n`;
  });

  register(gen, "board_base_inout_analog_read", (block, g) => {
    g.addImport("from machine import ADC, Pin");
    const pin = pinExpr(block, g);
    g.addSetup(`setup_adc_${pin}`, `adc_${pin} = ADC(Pin(${pin}))`);
    return [`adc_${pin}.read_u16()`, Order.FUNCTION_CALL];
  });

  register(gen, "board_base_inout_pin_mode", (block, g) => {
    g.addImport("from machine import Pin");
    const pin = pinExpr(block, g);
    const mode = block.getFieldValue("MODE");
    const mpMode =
      mode === "INPUT_PULLUP"
        ? "Pin.IN, Pin.PULL_UP"
        : mode === "INPUT"
          ? "Pin.IN"
          : "Pin.OUT";
    g.addSetup(`setup_mode_${pin}`, `pin_${pin} = Pin(${pin}, ${mpMode})`);
    return "";
  });

  register(gen, "board_serial_print", (block, g) => {
    const text = g.valueToCode(block, "CONTENT", Order.NONE) || "''";
    return `print(${text}, end='')\n`;
  });

  register(gen, "board_serial_println", (block, g) => {
    const text = g.valueToCode(block, "CONTENT", Order.NONE) || "''";
    return `print(${text})\n`;
  });

  register(gen, "comment", (block) => {
    const text = String(block.getFieldValue("TEXT") ?? "").replace(/\n/g, " ");
    return `# ${text}\n`;
  });
}
