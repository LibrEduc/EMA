/**
 * Prépare le corps d'une fonction Arduino (setup/loop) : indente les lignes
 * brutes (ex. pinMode via addSetup) sans double-indenter le code issu de
 * statementToCode (chaque ligne commence déjà par INDENT).
 */
export function formatFunctionBodyContent(
  content: string,
  indent = "  ",
): string {
  const trimmed = content.trimEnd();
  if (!trimmed) {
    return "";
  }
  return trimmed
    .split("\n")
    .map((line) => {
      if (!line.trim()) {
        return line;
      }
      if (line.startsWith(indent) || line.startsWith("\t")) {
        return line;
      }
      return indent + line;
    })
    .join("\n");
}

export type ArduinoSketchSections = {
  includes: unknown[];
  defines: unknown[];
  preamble: unknown[];
  variables: unknown[];
  codeFunctions: unknown[];
  userFunctions: unknown[];
  functionNames: unknown[];
  setups: unknown[];
  loop: unknown[];
  code: string;
  pinWarnings: string[];
};

/**
 * Format Arduino code with proper structure and spacing.
 * @param sections - Object containing all code sections.
 * @param indent - Indentation string (usually generator.INDENT).
 * @returns Formatted Arduino code.
 */
export function formatArduinoSketch(
  sections: ArduinoSketchSections,
  indent = "  ",
): string {
  const {
    includes,
    defines,
    preamble,
    variables,
    codeFunctions,
    userFunctions,
    setups,
    loop,
    code,
    pinWarnings,
  } = sections;

  const setupBody =
    setups.length > 0
      ? setups
          .map((entry) => formatFunctionBodyContent(String(entry), indent))
          .filter(Boolean)
          .join("\n")
      : "";
  const loopFromTags =
    loop.length > 0
      ? loop
          .map((entry) => formatFunctionBodyContent(String(entry), indent))
          .filter(Boolean)
          .join("\n")
      : "";
  const loopFromLoose = code.trim()
    ? formatFunctionBodyContent(code.trim(), indent)
    : "";
  const loopBody = [loopFromTags, loopFromLoose].filter(Boolean).join("\n");

  const emitSetup = setups.length > 0;
  const emitLoop = loop.length > 0 || Boolean(code.trim());
  const hasPreamble =
    includes.length > 0 ||
    defines.length > 0 ||
    preamble.length > 0 ||
    variables.length > 0 ||
    codeFunctions.length > 0 ||
    userFunctions.length > 0;
  const hasWarnings = pinWarnings.length > 0;

  if (!emitSetup && !emitLoop && !hasPreamble && !hasWarnings) {
    return "";
  }

  let arduinoCode = "";

  arduinoCode += "// Generated by µcBlockly Arduino Generator\n";
  arduinoCode += "// " + new Date().toISOString() + "\n\n";

  if (hasWarnings) {
    arduinoCode =
      "// WARNINGS:\n" +
      pinWarnings.map((w) => "// " + w).join("\n") +
      "\n\n" +
      arduinoCode;
  }

  if (includes.length > 0) {
    arduinoCode += includes.join("\n") + "\n\n";
  }

  if (defines.length > 0) {
    arduinoCode += defines.join("\n") + "\n\n";
  }

  if (preamble.length > 0) {
    arduinoCode += preamble.join("\n") + "\n\n";
  }

  if (variables.length > 0) {
    arduinoCode += variables.join("\n") + "\n\n";
  }

  if (codeFunctions.length > 0) {
    arduinoCode += codeFunctions.join("\n\n") + "\n\n";
  }

  if (userFunctions.length > 0) {
    arduinoCode += userFunctions.join("\n\n") + "\n\n";
  }

  if (emitSetup) {
    arduinoCode += "void setup() {\n";
    if (setupBody) {
      arduinoCode += setupBody + "\n";
    }
    arduinoCode += "}\n";
    if (emitLoop) {
      arduinoCode += "\n";
    }
  }
  if (emitLoop) {
    arduinoCode += "void loop() {\n";
    if (loopBody) {
      arduinoCode += loopBody + "\n";
    }
    arduinoCode += "}\n";
  }

  return arduinoCode;
}

/**
 * Validate pin usage map and return warning messages.
 */
export function validatePinUsageWarnings(
  pinUsages: Record<string, { number: string; mode: string; blockId: string }>,
): string[] {
  const warnings: string[] = [];
  for (const usage of Object.values(pinUsages)) {
    const pinNum = parseInt(usage.number, 10);
    if (Number.isNaN(pinNum) || pinNum < 0 || pinNum > 53) {
      warnings.push(`Warning: Pin ${usage.number} may be invalid for Arduino`);
    }
  }
  return warnings;
}
