import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SERVO = path.join(ROOT, "extensions", "servo");

test("servo pack: generated JS exports loader contracts", async () => {
  for (const file of [
    "blocks.js",
    "generator.arduino.js",
    "generator.micropython.js",
  ]) {
    const full = path.join(SERVO, file);
    assert.ok(fs.existsSync(full), `missing ${file}`);
    const text = fs.readFileSync(full, "utf8");
    assert.match(text, /GENERATED by `npm run build:extensions`/);
  }

  const blocksMod = await import(
    pathToFileURL(path.join(SERVO, "blocks.js")).href
  );
  assert.equal(typeof blocksMod.defineBlocks, "function");

  const arduinoMod = await import(
    pathToFileURL(path.join(SERVO, "generator.arduino.js")).href
  );
  assert.equal(typeof arduinoMod.registerArduinoGenerators, "function");

  const mpMod = await import(
    pathToFileURL(path.join(SERVO, "generator.micropython.js")).href
  );
  assert.equal(typeof mpMod.registerMicropythonGenerators, "function");
});

test("servo pack: Arduino generator registers servo_move", async () => {
  const { registerArduinoGenerators } = await import(
    pathToFileURL(path.join(SERVO, "generator.arduino.js")).href
  );
  const forBlock: Record<string, (b: { getFieldValue: (n: string) => string }) => string> =
    {};
  const arduinoGenerator = {
    forBlock,
    valueToCode: () => "90",
    addInclude: () => undefined,
    addDefinition: () => undefined,
    addSetup: () => undefined,
  };
  registerArduinoGenerators({
    arduinoGenerator,
    Order: { ATOMIC: 0 },
  });
  assert.equal(typeof forBlock.servo_move, "function");
  const code = forBlock.servo_move({
    getFieldValue: () => "SERVO1",
  });
  assert.match(String(code), /SERVO1\.write\(90\)/);
});
